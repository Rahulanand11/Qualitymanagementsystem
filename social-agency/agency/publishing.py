PUBLISH_MAX_ATTEMPTS = 40  # container processing polls count as attempts


# ------------------------------------------------------------------ approval
def decide_approval(post: Post, account: Account) -> tuple[bool, list[str]]:
    """Return (requires_approval, reasons). Exceptions always go to a human regardless of mode."""
    rules = (account.brand.automation_rules if account.brand else {}) or {}
    reasons: list[str] = []
    qc = post.qc or {}
    if account.autonomy_mode == "approval":
        reasons.append("Account is in approval-required mode")
    if post.content_source in ("fallback", ""):
        reasons.append("Copy was not generated by AI review (fallback draft)")
    if qc.get("blocking"):
        reasons.append("Quality checks failed")
    min_score = int(rules.get("min_qc_score", 85))
    if qc.get("score", 0) < min_score:
        reasons.append(f"QC score {qc.get('score', 0)} below threshold {min_score}")
    for flag in post.risk_flags or []:
        reasons.append(f"Risk: {flag}")
    for pm in post.media:
        a = pm.asset
        if not a.rights_confirmed:
            reasons.append(f"Content rights not confirmed for asset #{a.id}")
        if a.assignment_source not in ("folder", "filename", "sidecar", "dashboard"):
            reasons.append(f"Account assignment for asset #{a.id} is uncertain")
        if not (a.analysis or {}).get("ai"):
            reasons.append(f"Asset #{a.id} has no AI visual review")
    if account.autonomy_mode == "limited":
        allowed = rules.get("auto_formats", ["image", "carousel"])
        if post.format not in allowed:
            reasons.append(f"Format '{post.format}' is not in the auto-publish list {allowed}")
        pillars = rules.get("auto_pillars")
        if pillars and post.pillar not in pillars:
            reasons.append(f"Pillar '{post.pillar}' is not in the auto-publish list")
    if account.autonomy_mode == "full":
        blocked = rules.get("blocked_auto_formats", [])
        if post.format in blocked:
            reasons.append(f"Format '{post.format}' always needs approval for this account")
    return bool(reasons), reasons


def refresh_review_state(s: Session, post: Post, account: Account) -> None:
    post.qc = {**(post.qc or {}), **run_post_qc(post, account)}
    base_flags = [f for f in (post.risk_flags or []) if not f.startswith(("visual:", "qc:"))]
    qc_flags = [f"qc: {f}" if not f.startswith("visual:") else f for f in post.qc["risk_flags"]]
    post.risk_flags = sorted(set(base_flags + qc_flags))
    requires, reasons = decide_approval(post, account)
    post.requires_approval, post.approval_reasons = requires, reasons
    if post.status in ("draft", "needs_review", "approved"):
        post.status = "needs_review" if requires and not post.approved_by else "approved"


# ---------------------------------------------------------------- scheduling
def schedule_post(s: Session, post: Post, when: dt.datetime, source: str, actor: str = "system") -> None:
    if post.status not in ("approved", "scheduled", "failed"):
        raise ValueError(f"Only approved posts can be scheduled (status is {post.status})")
    conflict = s.scalar(select(Post).where(Post.account_id == post.account_id, Post.id != post.id,
                                           Post.status.in_(("scheduled", "publishing")),
                                           Post.scheduled_for.between(when - dt.timedelta(hours=2),
                                                                      when + dt.timedelta(hours=2))))
    if conflict is not None:
        raise ValueError(f"Conflicts with post #{conflict.id} scheduled at {conflict.scheduled_for} (min 2h gap)")
    post.scheduled_for, post.schedule_source, post.status, post.last_error = when, source, "scheduled", None
    for pm in post.media:
        pm.asset.status = "scheduled"
    audit(s, "post.scheduled", actor=actor, account_id=post.account_id, entity_type="post", entity_id=post.id,
          when=when.isoformat(), source=source)


def approve_post(s: Session, post: Post, actor: str) -> None:
    account = s.get(Account, post.account_id)
    refresh_review_state(s, post, account)
    if post.qc.get("blocking"):
        raise ValueError("This post has failing quality checks; fix them before approving")
    post.approved_by, post.status = actor, "approved"
    audit(s, "post.approved", actor=actor, account_id=post.account_id, entity_type="post", entity_id=post.id)


def scheduler_tick(s: Session) -> int:
    """Queue publish jobs for due posts. Nothing is queued while publishing is paused."""
    if publishing_globally_paused(s):
        return 0
    due = s.scalars(select(Post).where(Post.status == "scheduled", Post.scheduled_for <= utcnow())).all()
    queued = 0
    for post in due:
        account = s.get(Account, post.account_id)
        if account.publishing_paused:
            continue
        enqueue(s, "publish_post", {"post_id": post.id}, account_id=post.account_id,
                idempotency_key=f"publish:{post.id}:{post.scheduled_for.isoformat()}",
                max_attempts=PUBLISH_MAX_ATTEMPTS)
        queued += 1
    return queued


def media_url(derivative_id: int) -> str:
    return f"{get_settings().public_base_url}/public-media/{sign_media_token(derivative_id)}"


# ---------------------------------------------------------------- publishing
def _paused(s: Session, account: Account) -> bool:
    s.refresh(account)
    return publishing_globally_paused(s) or account.publishing_paused


@handler("publish_post")
def publish_post_job(s: Session, job: Job) -> dict:
    post = s.get(Post, job.payload["post_id"])
    account = s.get(Account, post.account_id)
    if post.status == "published" or (post.ig_media_id and post.status != "failed"):
        return {"skipped": "already published", "ig_media_id": post.ig_media_id}
    if post.status not in ("scheduled", "publishing"):
        return {"skipped": f"post status is {post.status}"}
    if _paused(s, account):
        post.status = "scheduled"
        job.idempotency_key = None  # let the scheduler queue a fresh job after resume
        return {"skipped": "publishing paused"}
    if post.requires_approval and not post.approved_by:
        raise PermanentError("Post requires approval and has not been approved")
    if not get_settings().public_media_ready:
        raise PermanentError("PUBLIC_BASE_URL must be a public HTTPS address so Instagram can fetch the media")
    if any(pm.asset.account_id != account.id for pm in post.media):
        raise PermanentError("Account isolation check failed: media belongs to a different account")

    if not post.ig_container_id:
        qc = run_post_qc(post, account)
        if qc["blocking"]:
            post.qc = {**(post.qc or {}), **qc}
            raise PermanentError("Pre-publish quality checks failed: " +
                                 "; ".join(c["detail"] or c["check"] for c in qc["checks"] if c["status"] == "fail"))
    post.status = "publishing"
    post.publish_attempts += 1
    try:
        client = client_for(s, account)
    except NotConnected as exc:
        raise PermanentError(str(exc)) from exc

    try:
        with client:
            if not post.ig_container_id:
                limit = client.publishing_limit()
                total = (limit.get("config") or {}).get("quota_total")
                if total is not None and limit.get("quota_usage", 0) >= total:
                    raise RetryableError(f"Instagram publishing limit reached ({limit.get('quota_usage')}/{total} in 24h)",
                                         delay_seconds=3600)
                if _duplicate_on_instagram(client, post):
                    raise PermanentError("An identical caption was published on this account in the last 25 posts")
                post.ig_container_id = _create_containers(client, post)
                audit(s, "post.container_created", account_id=account.id, entity_type="post", entity_id=post.id,
                      container_id=post.ig_container_id)
                s.commit()  # keep the container id even if a later step fails, so retries reuse it

            status = client.container_status(post.ig_container_id).get("status_code")
            if status == "IN_PROGRESS":
                raise RetryableError("Instagram is still processing the media", delay_seconds=30)
            if status in ("ERROR", "EXPIRED"):
                post.ig_container_id = None
                s.commit()
                raise PermanentError(f"Instagram rejected the media container ({status})")
            if status == "PUBLISHED":  # a previous attempt published but we did not record it
                media_id = _find_published(client, post)
                if not media_id:
                    raise RetryableError("Container is published but the media could not be located yet", 60)
            else:
                if _paused(s, account):
                    post.status = "scheduled"
                    job.idempotency_key = None
                    return {"skipped": "publishing paused before final publish step"}
                media_id = client.publish_container(post.ig_container_id)
            post.ig_media_id = media_id
            s.commit()
            try:
                item = client.media_item(media_id)
            except InstagramError:
                item = None
    except InstagramError as exc:
        if exc.kind == "rate_limit":
            raise RetryableError(str(exc), delay_seconds=exc.retry_after or 900) from exc
        if exc.kind == "transient":
            raise RetryableError(str(exc)) from exc
        if exc.kind == "auth":
            mark_auth_failure(s, account, str(exc))
            s.commit()
        raise PermanentError(str(exc)) from exc

    if item is None:
        enqueue(s, "verify_post", {"post_id": post.id}, account_id=account.id,
                idempotency_key=f"verify:{post.id}:{media_id}", max_attempts=8)
        return {"ig_media_id": media_id, "verified": False}
    _mark_published(s, post, account, item)
    return {"ig_media_id": media_id, "permalink": post.permalink, "verified": True}


def _create_containers(client, post: Post) -> str:
    caption = full_caption(post)
    items = post.media
    if post.format == "reel":
        pm = items[0]
        cover = media_url(pm.cover_derivative_id) if pm.cover_derivative_id else ""
        return client.create_video_container(media_url(pm.derivative_id), caption, cover_url=cover)
    if post.format == "image":
        return client.create_image_container(media_url(items[0].derivative_id), caption, alt_text=post.alt_text)
    children = []
    for pm in items:
        url = media_url(pm.derivative_id)
        if pm.asset.media_kind == "video":
            children.append(client.create_video_container(url, None, carousel_item=True))
        else:
            children.append(client.create_image_container(url, None, carousel_item=True))
    for child in children:
        client.wait_for_container(child, timeout=900)
    return client.create_carousel_container(children, caption)


def full_caption(post: Post) -> str:
    tags = " ".join(f"#{t}" for t in post.hashtags or [])
    return f"{post.caption.strip()}\n\n{tags}".strip() if tags else post.caption.strip()


def _norm(text: str) -> str:
    return " ".join((text or "").split()).lower()


def _duplicate_on_instagram(client, post: Post) -> bool:
    target = _norm(full_caption(post))
    return bool(target) and any(_norm(m.get("caption", "")) == target for m in client.media(limit=25, max_pages=1))


def _find_published(client, post: Post) -> str | None:
    target = _norm(full_caption(post))
    for m in client.media(limit=10, max_pages=1):
        if _norm(m.get("caption", "")) == target:
            return m["id"]
    return None


def _mark_published(s: Session, post: Post, account: Account, item: dict) -> None:
    from .models import MediaRecord

    post.status, post.permalink, post.last_error = "published", item.get("permalink"), None
    ts = item.get("timestamp")
    post.published_at = (dt.datetime.fromisoformat(ts.replace("+0000", "+00:00")).replace(tzinfo=None)
                         if ts else utcnow())
    rec = s.scalar(select(MediaRecord).where(MediaRecord.account_id == account.id,
                                             MediaRecord.ig_media_id == post.ig_media_id))
    if rec is None:
        rec = MediaRecord(account_id=account.id, ig_media_id=post.ig_media_id)
        s.add(rec)
    rec.post_id, rec.pillar = post.id, post.pillar
    rec.permalink, rec.caption, rec.posted_at = post.permalink or "", full_caption(post), post.published_at
    rec.media_type = item.get("media_type", "")
    rec.media_product_type = item.get("media_product_type", "")
    for pm in post.media:
        pm.asset.status = "published"
        _copy_to_folder(pm, account, "Published")
    audit(s, "post.published", account_id=account.id, entity_type="post", entity_id=post.id,
          ig_media_id=post.ig_media_id, permalink=post.permalink)
    notify(s, f"Published to @{account.ig_username or account.slug}", post.permalink or "", account_id=account.id,
           link=f"#/queue?post={post.id}")
    enqueue(s, "sync_media_insights", {"post_id": post.id}, account_id=account.id,
            idempotency_key=f"insights:{post.id}:24h", run_after=utcnow() + dt.timedelta(hours=24))


def _copy_to_folder(pm, account: Account, folder: str) -> None:
    if pm.derivative is None:
        return
    try:
        target = get_settings().watch_root / folder / account.folder_name
        target.mkdir(parents=True, exist_ok=True)
        src = pm.derivative.path
        shutil.copy2(src, target / f"post{pm.post_id}_{pm.position}_{pm.asset.filename.rsplit('.', 1)[0]}"
                                   f".{src.rsplit('.', 1)[-1]}")
    except OSError:
        pass


@handler("verify_post")
def verify_post_job(s: Session, job: Job) -> dict:
    post = s.get(Post, job.payload["post_id"])
    if post.status == "published":
        return {"skipped": "already verified"}
    account = s.get(Account, post.account_id)
    try:
        with client_for(s, account) as client:
            item = client.media_item(post.ig_media_id)
    except InstagramError as exc:
        raise RetryableError(f"Could not confirm publication yet: {exc}") from exc
    _mark_published(s, post, account, item)
    return {"verified": True, "permalink": post.permalink}


@on_dead("publish_post")
def _publish_failed(s: Session, job: Job) -> None:
    post = s.get(Post, job.payload["post_id"])
    if post is None or post.status == "published":
        return
    post.status, post.last_error = "failed", job.last_error
    for pm in post.media:
        pm.asset.status = "failed"
        pm.asset.status_reason = f"Publishing failed: {job.last_error}"
    audit(s, "post.publish_failed", account_id=post.account_id, entity_type="post", entity_id=post.id,
          error=job.last_error)
    notify(s, f"Publishing failed for post #{post.id}", job.last_error or "", level="error",
           account_id=post.account_id, link=f"#/queue?post={post.id}")


@on_dead("verify_post")
def _verify_failed(s: Session, job: Job) -> None:
    post = s.get(Post, job.payload["post_id"])
    if post and post.status != "published":
        post.last_error = "Instagram accepted the post but publication could not be confirmed. Check the account."
        notify(s, f"Unconfirmed publication for post #{post.id}", post.last_error, level="warning",
               account_id=post.account_id)


def set_global_pause(s: Session, paused: bool, actor: str) -> None:
    from .ops import set_setting

    set_setting(s, "publishing_paused", paused)
    audit(s, "publishing.paused" if paused else "publishing.resumed", actor=actor)
    notify(s, "Publishing paused" if paused else "Publishing resumed", f"by {actor}",
           level="warning" if paused else "info")


def retry_failed_post(s: Session, post: Post, actor: str) -> None:
    if post.status != "failed":
        raise ValueError("Only failed posts can be retried")
    post.status, post.last_error = "scheduled", None
    post.scheduled_for = utcnow()
    for pm in post.media:
        pm.asset.status, pm.asset.status_reason = "scheduled", ""
    audit(s, "post.retry", actor=actor, account_id=post.account_id, entity_type="post", entity_id=post.id)


def assets_of(post: Post) -> list[Asset]:
    return [pm.asset for pm in post.media]
